import puppeteer from 'puppeteer-core';
const browser=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.setViewport({width:1440,height:1100,deviceScaleFactor:1});
await page.goto('http://localhost:8000',{waitUntil:'networkidle0'});
await page.screenshot({path:'screenshots/desktop.jpg',type:'jpeg',quality:85,fullPage:true});
await page.click('[data-save="reach"]');
await page.click('#my-acts');
if(await page.$eval('#act-count',el=>el.textContent)!=='1')throw new Error('Bookmark count');
await page.screenshot({path:'screenshots/saved.jpg',type:'jpeg',quality:80});
await page.click('[data-revisit="reach"]');
await page.type('#reflection','Sam');
await page.click('#next-step');
await page.type('#reflection','Hey Sam, I really appreciated your help. How have you been?');
await page.click('#back-step');
if(await page.$eval('#reflection',el=>el.value)!=='Sam')throw new Error('Note retention');
await page.click('#next-step');
await page.click('#next-step');
await page.click('[data-check="0"]');
await page.click('#next-step');
if(!await page.$eval('#action-title',e=>e.textContent.includes('little good')))throw new Error('Completion');
await page.screenshot({path:'screenshots/completed.jpg',type:'jpeg',quality:80});
await page.click('#done-action');
await page.click('[data-category="care"]');
if(await page.$$eval('.action-card',els=>els.length)!==1)throw new Error('Category filter');
await page.click('[data-open="reset"]');
await page.click('#next-step');
await page.click('#breath-toggle');
if(!await page.$('.breath-orb.running'))throw new Error('Breathing focus');
await page.keyboard.press('Escape');
await page.click('[data-category="help"]');
await page.select('#time-filter','2');
if(!await page.$('.empty-results'))throw new Error('Empty state');
await page.click('#reset-filters');
await page.click('#show-more');
if(await page.$$eval('.action-card',els=>els.length)!==6)throw new Error('Show all');
await page.click('[data-about]');
await page.keyboard.press('Escape');
await page.click('#privacy');
await page.keyboard.press('Escape');
await page.reload({waitUntil:'networkidle0'});
if(await page.$eval('#act-count',el=>el.textContent)!=='0')throw new Error('Session reset');
await page.setViewport({width:390,height:844,deviceScaleFactor:1});
await page.screenshot({path:'screenshots/mobile.jpg',type:'jpeg',quality:85,fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
if(overflow)throw new Error('Mobile horizontal overflow');
await page.click('[data-open="pause"]');
await page.screenshot({path:'screenshots/mobile-dialog.jpg',type:'jpeg',quality:85});
console.log(JSON.stringify({errors,desktop:'1440px',mobile:'390px',passed:['bookmarks','guided steps','note retention','completion','category filters','time filters','empty state','breathing focus','show all','about and privacy','session reset','mobile overflow']}));
await browser.close();

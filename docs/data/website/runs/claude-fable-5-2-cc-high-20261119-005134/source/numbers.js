export function byCode(code) {
  return COUNTRIES.find((c) => c.code === code) || UNKNOWN;
}

/** Guess the visitor's country without any network request. */
export function guessCountry() {
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
    if (TZ[tz]) return byCode(TZ[tz]);
    for (const key of Object.keys(TZ)) {
      if (key.endsWith("/") && tz.startsWith(key)) return byCode(TZ[key]);
    }
  } catch (e) {
    /* fall through */
  }
  return UNKNOWN;
}

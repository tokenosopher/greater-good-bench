// Embeds the two typefaces as data URLs so the page needs no network and no asset loaders.
import { readFileSync, writeFileSync } from "node:fs";
const b64 = (p) => readFileSync(new URL(p, import.meta.url)).toString("base64");
const archivo = b64("../node_modules/@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2");
const atkinson = b64("../node_modules/@fontsource-variable/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-wght-normal.woff2");
const css = `/* Generated by tools/make-fonts.mjs — do not edit by hand. */
@font-face{font-family:"Archivo";font-style:normal;font-display:swap;font-weight:100 900;font-stretch:62% 125%;src:url(data:font/woff2;base64,${archivo}) format("woff2");}
@font-face{font-family:"Atkinson Next";font-style:normal;font-display:swap;font-weight:200 800;src:url(data:font/woff2;base64,${atkinson}) format("woff2");}
`;
writeFileSync(new URL("../fonts.css", import.meta.url), css);
console.log("fonts.css", (css.length / 1024).toFixed(0) + " KB");

export default async ({ page, shot, sleep, clickText, clickLabel }) => {
  await clickText("Bleeding", ".card");
  await sleep(2500);
  await shot("bl-1a");
  const el = await page.$('[aria-label*="Press and hold"]');
  const b = await el.boundingBox();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
  await page.mouse.down();
  await sleep(3000);
  await shot("bl-1b");
  await page.mouse.up();
  await sleep(600);
  await shot("bl-1c");
  await page.mouse.down();
  await sleep(8400);
  await page.mouse.up();
  await sleep(300);
  await shot("bl-1d");
  await clickText("Next step");
  await sleep(500);
  await shot("bl-2a");
  await clickText("Take it off");
  await sleep(200);
  await clickText("Put another on top");
  await sleep(300);
  await shot("bl-2b");
  await clickText("Next step");
  await sleep(500);
  await shot("bl-3a");
  await clickLabel("On the elbow");
  await sleep(200);
  await clickLabel("above the wound");
  await sleep(1700);
  await shot("bl-3b");
};
